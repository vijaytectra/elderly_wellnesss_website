#!/usr/bin/env node
/**
 * Generates css/ew-carousel-reserve.css: a per-carousel height reservation so
 * the page does not jump when Owl initialises.
 *
 * owl.carousel.min.css ships `.owl-carousel{display:none}` and Owl only reveals
 * the element once its JS has run, so every carousel occupies 0px and then
 * snaps to full height, pushing everything below it down. On about.html that
 * was a 350px jump worth 0.34 CLS on its own.
 *
 * An earlier attempt reserved the space by revealing the first slide before
 * init. That corrupted Owl's own width measurement on `autoWidth` carousels
 * (#about_slider laid out as two rows, doubling 350px -> 700px), so instead
 * this measures each carousel's real initialised height in a headless browser
 * and emits a plain min-height for the pre-init state only. Items stay hidden,
 * so Owl measures exactly what it measured before.
 *
 * Usage: node scripts/measure-carousel-heights.js <base-url>
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CHROME = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const puppeteer = require(path.join(process.env.PUPPETEER_PATH || ROOT, 'node_modules', 'puppeteer-core'));

const BASE = process.argv[2] || 'http://127.0.0.1:5556';

const PAGES = [
  '/', '/about.html', '/contact.html', '/elderly-wellness.html',
  '/how-elderly-wellness-works.html', '/investors.html', '/board-of-advisors.html',
  '/nursing-services-for-elders.html', '/physiotherapy-services-for-elders.html',
  '/geriatric-care-services-for-elders.html',
  '/assisted-living-support-services-for-elders.html',
];

const BREAKPOINTS = [
  { name: 'mobile', width: 412, query: '(max-width: 767px)' },
  { name: 'tablet', width: 900, query: '(min-width: 768px) and (max-width: 1199px)' },
  { name: 'desktop', width: 1440, query: '(min-width: 1200px)' },
];

(async () => {
  const browser = await puppeteer.launch({
    executablePath: CHROME, headless: 'new', args: ['--no-sandbox', '--disable-gpu'],
  });

  // breakpoint -> { carouselId -> max measured height }
  const heights = {};
  for (const bp of BREAKPOINTS) heights[bp.name] = {};

  for (const bp of BREAKPOINTS) {
    const page = await browser.newPage();
    await page.setViewport({ width: bp.width, height: 900, deviceScaleFactor: 1, isMobile: bp.width < 768 });

    for (const p of PAGES) {
      try {
        await page.goto(BASE + p, { waitUntil: 'networkidle2', timeout: 60000 });
        // Scroll so lazily-initialised carousels come up, then let the sweep run.
        await page.evaluate(async () => {
          await new Promise((r) => {
            let y = 0;
            const t = setInterval(() => {
              window.scrollTo(0, (y += 800));
              if (y > document.body.scrollHeight) { clearInterval(t); window.scrollTo(0, 0); r(); }
            }, 30);
          });
        });
        await new Promise((r) => setTimeout(r, 5000));

        const found = await page.evaluate(() =>
          [...document.querySelectorAll('.owl-carousel.owl-loaded')]
            .filter((el) => el.id)
            .map((el) => [el.id, Math.round(el.getBoundingClientRect().height)])
        );

        for (const [id, h] of found) {
          if (!h) continue;
          heights[bp.name][id] = Math.max(heights[bp.name][id] || 0, h);
        }
      } catch (e) {
        console.log(`  ! ${p} @${bp.name}: ${e.message.slice(0, 60)}`);
      }
    }
    await page.close();
    console.log(`  ${bp.name.padEnd(8)} measured ${Object.keys(heights[bp.name]).length} carousels`);
  }
  await browser.close();

  let css =
    '/*\n' +
    ' * GENERATED by scripts/measure-carousel-heights.js -- do not hand-edit.\n' +
    ' *\n' +
    ' * Owl hides .owl-carousel until its JS runs, so each carousel occupied 0px\n' +
    ' * and then snapped to full height, shifting everything below it. These\n' +
    ' * reservations hold the space up-front; they stop applying the moment Owl\n' +
    ' * adds .owl-loaded, so initialised behaviour is untouched.\n' +
    ' *\n' +
    ' * Items stay display:none pre-init so Owl measures exactly what it always did.\n' +
    ' * Must be concatenated AFTER owl.carousel.min.css.\n' +
    ' */\n' +
    '.owl-carousel:not(.owl-loaded){display:block}\n' +
    '.owl-carousel:not(.owl-loaded)>.item{display:none}\n';

  for (const bp of BREAKPOINTS) {
    const ids = Object.keys(heights[bp.name]).sort();
    if (!ids.length) continue;
    const rules = ids.map((id) => `#${id}:not(.owl-loaded){min-height:${heights[bp.name][id]}px}`).join('');
    css += `@media ${bp.query}{${rules}}\n`;
    console.log(`  ${bp.name}: ${ids.map((i) => i + '=' + heights[bp.name][i] + 'px').join(' ')}`);
  }

  fs.writeFileSync(path.join(ROOT, 'css', 'ew-carousel-reserve.css'), css);
  console.log(`\n  wrote css/ew-carousel-reserve.css (${css.length} bytes)`);
})().catch((e) => { console.error(e); process.exit(1); });
